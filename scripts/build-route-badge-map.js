#!/usr/bin/env node
// Builds data/route-achievements.json — the route -> achievement (badge) ID map.
//
// Source is Zwift's own GameDictionary.xml (routes and achievements both), so
// this needs no credentials and stays current with the game rather than with an
// npm package. Route badges are the achievements with imageName=RouteComplete;
// their `sport` field (0 cycling, 1 running) disambiguates the routes that have
// one badge per sport. The join is by normalised name plus a hand-verified
// override table for routes Zwift renamed after the badge shipped. Nothing is
// fuzzy-matched.
//
//   REPORT=1 node scripts/build-route-badge-map.js     (audit)
//   EMIT=1   node scripts/build-route-badge-map.js     (write JSON)
import { writeFileSync } from 'node:fs';
import { load } from '../src/gamedict.js';

export const norm = (s) =>
  s.normalize('NFD').replace(/[̀-ͯ]/g, '').toUpperCase()
    .replace(/[’']/g, '').replace(/&/g, 'AND')
    .replace(/\((CYCLING|RUNNING)\)/g, '')
    .replace(/[^A-Z0-9]+/g, ' ').trim();

// Route name -> badge name, for routes renamed after their badge shipped.
// Each confirmed by world, distance and XP against the badge wording.
const OVERRIDES = {
  'Watopia Flat Route': 'FLAT ROUTE',
  'Watopia Hilly Route': 'HILLY ROUTE',
  'Watopia Mountain Route': 'MOUNTAIN ROUTE',
  'Watopia Mountain 8': 'MOUNTAIN 8',
  'Watopia Figure 8': 'FIGURE 8',
  'Watopia Figure 8 Reverse': 'FIGURE 8 REVERSE',
  'Watopia Pretzel': 'THE PRETZEL',
  'London PRL Half': 'THE PRL HALF',
  'London PRL FULL': 'THE PRL FULL',
  'Richmond UCI Worlds': '2015 UCI WORLDS COURSE',
  'Richmond 2015 Worlds Reverse': 'RICHMOND UCI REVERSE',
  '2018 Worlds Short Lap': '2018 UCI WORLDS SHORT LAP',
  '2019 Worlds Harrogate Circuit': '2019 UCI WORLDS HARROGATE CIRCUIT',
  WhatYumeziWereLost: 'WHAT YUMEZI WERE LOST',
};

const { routes, achievements, source } = load();
const badges = achievements.filter((a) => a.isRouteCompletion);

const byName = new Map();
for (const b of badges) {
  const k = norm(b.name);
  if (!byName.has(k)) byName.set(k, []);
  byName.get(k).push(b);
}

const mapped = [];
const unmatched = [];
const ambiguous = [];

for (const r of routes) {
  const cand = byName.get(norm(OVERRIDES[r.name] ?? r.name));
  if (!cand) { unmatched.push(r); continue; }
  // A route ridden in both sports can have a badge per sport; pick by the
  // route's own sport rather than guessing from the badge's name.
  let pick = cand;
  if (cand.length > 1) {
    const want = r.cycling ? 0 : 1;
    const bySport = cand.filter((b) => b.sport === want);
    if (bySport.length === 1) pick = bySport;
  }
  if (pick.length > 1) { ambiguous.push({ route: r, cand: pick }); continue; }
  mapped.push({ routeId: r.id, name: r.name, world: r.world, achievementId: pick[0].id, badgeName: pick[0].name, sport: pick[0].sport, via: OVERRIDES[r.name] ? 'override' : 'name' });
}

const usedIds = new Set(mapped.map((m) => m.achievementId));
const orphanBadges = badges.filter((b) => !usedIds.has(b.id));
const inScope = (r) => r.cycling && !r.eventOnly && !r.isPortal;

if (process.env.EMIT === '1') {
  writeFileSync(new URL('../data/route-achievements.json', import.meta.url), JSON.stringify({
    _comment: 'Route -> Zwift achievement (badge) ID. Generated by scripts/build-route-badge-map.js from GameDictionary.xml. MIT.',
    _source: 'https://cdn.zwift.com/gameassets/GameDictionary.xml',
    _generatedAt: new Date().toISOString().slice(0, 10),
    _counts: { routes: routes.length, badges: badges.length, mapped: mapped.length, unmatched: unmatched.length, orphanBadges: orphanBadges.length },
    _unmappableBadges: orphanBadges.map((b) => ({ id: b.id, name: b.name, sport: b.sport })),
    byRouteId: Object.fromEntries(mapped.map((m) => [m.routeId, m.achievementId])),
  }, null, 2) + '\n');
  console.log('wrote data/route-achievements.json');
}

if (process.env.REPORT === '1') {
  console.log('source                :', source);
  console.log('routes                :', routes.length);
  console.log('RouteComplete badges  :', badges.length, `(cycling ${badges.filter((b) => b.sport === 0).length}, running ${badges.filter((b) => b.sport === 1).length})`);
  console.log('mapped                :', mapped.length, `(${mapped.filter((m) => m.via === 'override').length} via override)`);
  console.log('ambiguous             :', ambiguous.length);
  console.log('unmatched routes      :', unmatched.length,
    `(portal climbs: ${unmatched.filter((r) => r.isPortal).length}, event-only: ${unmatched.filter((r) => r.eventOnly && !r.isPortal).length}, in-scope: ${unmatched.filter(inScope).length})`);
  console.log('badges with no route  :', orphanBadges.length);
  const scoped = routes.filter(inScope);
  console.log('\nIN-SCOPE COVERAGE:', scoped.filter((r) => mapped.some((m) => m.routeId === r.id)).length + '/' + scoped.length);
  if (unmatched.filter(inScope).length) {
    console.log('\n--- IN-SCOPE UNMATCHED ---');
    unmatched.filter(inScope).forEach((r) => console.log('  ' + r.name.padEnd(34) + (r.world ?? '?')));
  }
  if (orphanBadges.length) { console.log('\n--- ORPHAN BADGES ---'); orphanBadges.forEach((b) => console.log('  ' + String(b.id).padStart(4) + '  ' + b.name + '  sport=' + b.sport)); }
  if (ambiguous.length) { console.log('\n--- AMBIGUOUS ---'); ambiguous.forEach((a) => console.log('  ' + a.route.name + ' -> ' + a.cand.map((c) => `${c.id}(sport ${c.sport})`).join(', '))); }
}
